    public static async Task<object> RunAsync(SpikeTarget target)
    {
        await using var admin = await target.OpenAsync(target.AdminUser, 2);
        var results = new List<object>();

        foreach (var probe in Cases)
        {
            results.Add(await RunCaseAsync(admin.DataSource, probe));
        }

        results.Add(await SchemaLimitAsync(admin.DataSource));

        return new { scenario = "probe", engine = target.Engine.ToString(), results };
    }

    private static async Task<object> RunCaseAsync(NpgsqlDataSource dataSource, Case probe)
    {
        await using var conn = await dataSource.OpenConnectionAsync();
        var steps = new List<object>();
        var ok = true;
        string? output = null;

        foreach (var statement in probe.Statements)
        {
            var r = await Sql.TryAsync(async () =>
            {
                await using var cmd = new NpgsqlCommand(statement, conn);
                await using var reader = await cmd.ExecuteReaderAsync();
                var lines = new List<string>();
                do
                {
                    while (await reader.ReadAsync())
                    {
                        lines.Add(string.Join(" | ", Enumerable.Range(0, reader.FieldCount).Select(i => reader.IsDBNull(i) ? "null" : Convert.ToString(reader.GetValue(i), System.Globalization.CultureInfo.InvariantCulture))));
                    }
                }
                while (await reader.NextResultAsync());

                if (lines.Count > 0)
                {
                    output = string.Join("\n", lines.Take(40));
                }
            });

            steps.Add(new { statement = Shorten(statement), r.Ok, r.SqlState, r.Message, ms = Math.Round(r.Ms, 1) });
            if (!r.Ok)
            {
                ok = false;
                await Sql.TryAsync(() => Sql.ExecAsync(conn, "ROLLBACK"));
                break;
            }
        }

        return new { id = probe.Id, topic = probe.Topic, ok, steps, output };
    }

    /// <summary>Creates empty schemas until the engine refuses, then drops them again.</summary>
    private static async Task<object> SchemaLimitAsync(NpgsqlDataSource dataSource)
    {
        await using var conn = await dataSource.OpenConnectionAsync();
        const string userSchemas =
            "SELECT nspname FROM pg_catalog.pg_namespace WHERE nspname NOT LIKE 'pg\\_%' AND nspname NOT IN ('information_schema', 'sys') ORDER BY nspname";
        var before = (await Sql.RowsAsync(conn, userSchemas)).Select(r => (string)r[0]!).ToArray();

        var created = new List<string>();
        (bool Ok, string? SqlState, string? Message, double Ms) refusal = default;
        for (var i = 1; i <= 15; i++)
        {
            var name = $"spike_limit_{i}";
            var r = await Sql.TryAsync(() => Sql.ExecAsync(conn, $"CREATE SCHEMA {name}"));
            if (!r.Ok)
            {
                refusal = r;
                break;
            }

            created.Add(name);
        }

        var during = (await Sql.RowsAsync(conn, userSchemas)).Select(r => (string)r[0]!).ToArray();
        foreach (var name in created)
        {
            await Sql.TryAsync(() => Sql.ExecAsync(conn, $"DROP SCHEMA {name}"));
        }

        return new
        {
            id = "limit.schemas",
            topic = "limits",
            schemasBefore = before,
            createdBeforeRefusal = created.Count,
            schemasAtLimit = during,
            refusal = refusal.Ok ? null : new { refusal.SqlState, refusal.Message }
        };
    }

    private static string Shorten(string sql) => sql.Length <= 140 ? sql : sql[..137] + "...";
